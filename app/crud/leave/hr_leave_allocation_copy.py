def run_monthly_leave_cron(db):

    today   = date.today()
    year    = today.year
    quarter = current_quarter(today)

    print(f"\n{'='*60}")
    print(f"LEAVE CRON | {today} | Year={year} | Q{quarter}")
    print(f"{'='*60}\n")

    # ── Step 1: Auto-confirm probation employees ──────────────
    auto_confirm_employees(db)

    # ── Step 2: Load users ────────────────────────────────────
    users = db.execute(text("""
        SELECT user_id,
               employment_type,
               date_of_joining,
               probation_from,
               probation_to,
               permanent_from
        FROM users
        WHERE employment_type IN ('Permanent', 'Probation')
          AND is_deleted = FALSE
    """)).mappings().all()

    print(f"Loaded {len(users)} users\n")

    # ── Step 3: Load leave type IDs ───────────────────────────
    leave_types = {
        r.code: r.type_id
        for r in db.execute(text("SELECT type_id, code FROM leave_types"))
    }

    CL    = leave_types["CL"]
    HPL   = leave_types["HPL"]
    EL_E  = leave_types["EL_E"]
    EL_NE = leave_types["EL_NE"]
    RH    = leave_types["RH"]

    print(f"Leave types → CL={CL} HPL={HPL} EL_E={EL_E} EL_NE={EL_NE} RH={RH}\n")

    # ==================================================
    # ANNUAL LEAVES (CL + HPL + RH)
    # ==================================================

    print("── ANNUAL LEAVES ──────────────────────────────────────")

    for u in users:
        uid = u["user_id"]

        # ── RH: 2 per year for everyone ───────────────────────
        rh_exists = db.execute(text("""
            SELECT 1 FROM leave_balances
            WHERE user_id   = :uid
              AND type_id   = :rh
              AND leave_year = :yr
        """), {"uid": uid, "rh": RH, "yr": year}).first()

        if not rh_exists:
            _insert_rh_balance(db, uid, RH, 2)
            print(f"  RH | user={uid} qty=2")

        # ── PROBATION → CL only ───────────────────────────────
        if u["employment_type"] == "Probation":
            cl_exists = db.execute(text("""
                SELECT 1 FROM leave_balances
                WHERE user_id   = :uid
                  AND type_id   = :cl
                  AND leave_year = :yr
            """), {"uid": uid, "cl": CL, "yr": year}).first()

            if cl_exists:
                continue

            elig_date = u.get("probation_from") or u.get("date_of_joining")
            if not elig_date:
                continue

            cl_qty = CL_BY_MONTH[1] if elig_date.year < year \
                     else CL_BY_MONTH[elig_date.month]
            _insert_balance(db, uid, CL, cl_qty)
            print(f"  CL | user={uid} qty={cl_qty} [Probation]")

        # ── PERMANENT → CL + HPL ──────────────────────────────
        elif u["employment_type"] == "Permanent":
            start_year, start_month = effective_start_month(u, year)
            if not start_year:
                print(f"  SKIP annual | user={uid} — missing DOJ/permanent_from")
                continue

            if start_year < year:
                cl_qty, hpl_qty = CL_BY_MONTH[1], HPL_BY_MONTH[1]
            elif start_year == year:
                cl_qty, hpl_qty = CL_BY_MONTH[start_month], HPL_BY_MONTH[start_month]
            else:
                print(f"  SKIP annual | user={uid} — starts future year {start_year}")
                continue

            cl_exists = db.execute(text("""
                SELECT 1 FROM leave_balances
                WHERE user_id   = :uid
                  AND type_id   = :cl
                  AND leave_year = :yr
            """), {"uid": uid, "cl": CL, "yr": year}).first()

            if not cl_exists:
                _insert_balance(db, uid, CL, cl_qty)
                print(f"  CL | user={uid} qty={cl_qty} [Permanent]")

            hpl_exists = db.execute(text("""
                SELECT 1 FROM leave_balances
                WHERE user_id   = :uid
                  AND type_id   = :hpl
                  AND leave_year = :yr
            """), {"uid": uid, "hpl": HPL, "yr": year}).first()

            if not hpl_exists:
                _insert_balance(db, uid, HPL, hpl_qty)
                print(f"  HPL | user={uid} qty={hpl_qty} [Permanent]")

    # ==================================================
    # QUARTERLY EL (Permanent only)
    # ==================================================

    print("\n── QUARTERLY EL ───────────────────────────────────────")

    for u in users:
        if u["employment_type"] != "Permanent":
            continue

        uid = u["user_id"]

        # ── Already allocated this quarter? ───────────────────
        el_exists = db.execute(text("""
            SELECT 1 FROM leave_balances
            WHERE user_id   = :uid
              AND type_id  IN (:el_e, :el_ne)
              AND leave_year = :yr
              AND DATE_PART('quarter', created_date) = :qr
        """), {
            "uid": uid, "el_e": EL_E, "el_ne": EL_NE,
            "yr": year, "qr": quarter,
        }).first()

        if el_exists:
            print(f"  SKIP EL | user={uid} — already allocated Q{quarter} {year}")
            continue

        # ── Eligibility ───────────────────────────────────────
        # EL eligibility is based on permanent_from (when they became permanent).
        # DOJ is only a fallback if permanent_from is missing.
        # NEVER use max(DOJ, permanent_from) — DOJ can be a future date
        # and would incorrectly override permanent_from.
        doj  = u.get("date_of_joining")
        perm = u.get("permanent_from")

        if not perm and not doj:
            print(f"  SKIP EL | user={uid} — no permanent_from and no DOJ")
            continue

        # Use permanent_from if available, else fall back to DOJ
        elig   = perm if perm else doj
        elig_q = ((elig.month - 1) // 3) + 1

        if elig.year > year or (elig.year == year and elig_q > quarter):
            print(f"  SKIP EL | user={uid} — not eligible yet (elig={elig} Q{elig_q})")
            continue

        # ── Quarter month index ───────────────────────────────
        q_month_idx = 1 if (elig.year < year or elig_q < quarter) \
                      else ((elig.month - 1) % 3) + 1

        enc, non, total_new = calculate_el_for_quarter(q_month_idx)
        current             = _current_el_balance(db, uid, EL_E, EL_NE)
        projected           = current + total_new

        print(f"  EL | user={uid} current={current} +{total_new} projected={projected} q_idx={q_month_idx}")

        # ── Cap logic ─────────────────────────────────────────
        if projected >= 292:
            process_el_allocation(
                db=db, user=u, current=current,
                enc=enc, non=non, EL_E=EL_E, EL_NE=EL_NE,
            )
        else:
            _insert_balance(db, uid, EL_E,  enc)
            _insert_balance(db, uid, EL_NE, non)
            print(f"  EL allocated | user={uid} EL_E={enc} EL_NE={non}")

        # ── Safety guard ──────────────────────────────────────
        final = _current_el_balance(db, uid, EL_E, EL_NE)
        assert final <= MAX_EL, \
            f"❌ EL exceeded cap! user={uid} balance={final}"

    # ==================================================
    # Disable previous-year CL
    # ==================================================

    print("\n── DISABLING OLD CL ───────────────────────────────────")
    db.execute(text("""
        UPDATE leave_balances
        SET is_usable = FALSE
        WHERE type_id   = :cl
          AND leave_year < :yr
    """), {"cl": CL, "yr": year})

    db.commit()
    print("\n✅ Monthly leave cron completed successfully.")