# ==================================================

def process_el_allocation(db, user, current, enc, non, EL_E, EL_NE):
    """
    Called when projected EL >= 292.

    BUG 5 FIX: old code did `if opening < 292: return` — nothing happened
    when current was e.g. 290 but projected was 298.
    Now falls back to a headroom-capped normal insert.

    BUG 6 FIX: force inserts use DO UPDATE so qty=0 rows are always written.
    """
    opening = min(current, MAX_EL)

    print(f"  [PROCESS EL] user={user['user_id']} current={current} opening={opening}")

    # BUG 5 FIX: was `if opening < 292: return`
    if opening < 292:
        headroom = MAX_EL - current
        safe_enc = min(enc, headroom)
        safe_non = min(non, max(headroom - safe_enc, 0))
        print(f"  [PROCESS EL] opening<292 fallback enc={safe_enc} non={safe_non}")
        _insert_balance(db, user["user_id"], EL_E,  safe_enc)
        _insert_balance(db, user["user_id"], EL_NE, safe_non)
        return

    row             = EL_HARDCODED_TABLE[opening]
    enc_to_allocate = row["enc"]
    non_to_allocate = row["non"]
    auto_encash     = row["encash"]

    print(f"  [PROCESS EL] table[{opening}] → enc={enc_to_allocate} non={non_to_allocate} encash={auto_encash}")

    # BUG 6 FIX: force=True + DO UPDATE guarantees these rows are written
    _insert_balance(db, user["user_id"], EL_E,  enc_to_allocate, force=True)
    _insert_balance(db, user["user_id"], EL_NE, non_to_allocate, force=True)

    # Encashment created only when opening > 292 (292 row has encash=0)
    if opening > 292:
        mid = create_encashment_main(db, user["user_id"])
        create_leave_encashment(
            db=db,
            mid=mid,
            user_id=user["user_id"],
            encash_qty=auto_encash,
            balance=current,
        )

    final_balance = opening + enc_to_allocate + non_to_allocate
    assert final_balance == MAX_EL, \
        f"❌ EL cap mismatch user={user['user_id']}: {final_balance} != {MAX_EL}"
    print(f"  [PROCESS EL] ✅ final balance = {final_balance}")


